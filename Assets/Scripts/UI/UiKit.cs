/// <summary>
/// Mazraa UI art kit: 9-slice panels / buttons / bars (Resources/UI/Kit), 120+ flat icons (Resources/UI/Icons, white,
/// tinted through Image.color) and controller / key glyphs (Resources/UI/Glyphs). All sprites are generated by
/// Branding/make_ui_kit.py (original art); the 9-slice borders come from Resources/UI/kit_manifest.json so the runtime
/// sprite (Sprite.Create with a border) matches the importer settings. Everything degrades to flat colours when a
/// sprite is missing, so code-built screens never break.
/// </summary>
public static class UiKit
{
    [Serializable] private class Manifest { public List<string> icons; public List<string> glyphs; }

    private static readonly Dictionary<string, Sprite> cache = new Dictionary<string, Sprite>();
    private static Dictionary<string, Vector4> borders;
    private static HashSet<string> iconNames, glyphNames;
    private static bool loaded;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
    private static void ResetStatics() { cache.Clear(); borders = null; iconNames = null; glyphNames = null; loaded = false; }

    // Brand colours used by the kit (BRAND.md)
    public static readonly Color Gold = new Color(0.98f, 0.76f, 0.25f);
    public static readonly Color Sand = new Color(0.91f, 0.85f, 0.71f);
    public static readonly Color PalmDark = new Color(0.086f, 0.227f, 0.125f);
    public static readonly Color Brown = new Color(0.17f, 0.106f, 0.055f);
    public static readonly Color Mint = new Color(0.61f, 0.88f, 0.48f);

    /// <summary>True once the kit sprites were found in Resources (false in a build that stripped them).</summary>
    public static bool Enabled { get { Load(); return borders != null && borders.Count > 0; } }

    private static void Load()
    {
        if (loaded) return;
        loaded = true;
        borders = new Dictionary<string, Vector4>();
        iconNames = new HashSet<string>(); glyphNames = new HashSet<string>();
        var ta = Resources.Load<TextAsset>("UI/kit_manifest");
        if (ta == null) return;
        try
        {
            // borders: {"name": [l, b, r, t]} - parsed by hand (JsonUtility cannot read a dictionary)
            string t = ta.text;
            int b0 = t.IndexOf("\"borders\"", StringComparison.Ordinal);
            int open = t.IndexOf('{', b0 + 9), close = t.IndexOf('}', open);
            foreach (var entry in t.Substring(open + 1, close - open - 1).Split(']'))
            {
                int q = entry.IndexOf('"'); if (q < 0) continue;
                int q2 = entry.IndexOf('"', q + 1);
                string name = entry.Substring(q + 1, q2 - q - 1);
                string nums = entry.Substring(entry.IndexOf('[') + 1);
                var p = nums.Split(',');
                if (p.Length == 4) borders[name] = new Vector4(F(p[0]), F(p[1]), F(p[2]), F(p[3]));
            }
            var m = JsonUtility.FromJson<Manifest>(t);
            if (m != null && m.icons != null) foreach (var n in m.icons) iconNames.Add(n);
            if (m != null && m.glyphs != null) foreach (var n in m.glyphs) glyphNames.Add(n);
        }
        catch (Exception e) { Debug.LogWarning("[UiKit] kit_manifest.json could not be read: " + e.Message); }
    }

    private static float F(string s) => float.Parse(s.Trim(), System.Globalization.CultureInfo.InvariantCulture);

    /// <summary>9-slice kit sprite (panel, button, button_selected, bar_track, bar_fill, tab, card, divider, ...).</summary>
    public static Sprite Kit(string name)
    {
        Load();
        Vector4 border;
        if (!borders.TryGetValue(name, out border)) border = Vector4.zero;
        return Get("UI/Kit/" + name, border);
    }

    /// <summary>Flat icon by name (money, fuel, crop_wheat, animal_cow, vehicle_tractor, poi_market, settings, ...).</summary>
    public static Sprite Icon(string name) { Load(); return iconNames.Contains(name) ? Get("UI/Icons/" + name, Vector4.zero) : null; }

    public static bool HasIcon(string name) { Load(); return iconNames.Contains(name); }
    public static bool HasGlyph(string name) { Load(); return glyphNames.Contains(name); }
    public static IEnumerable<string> IconNames { get { Load(); return iconNames; } }
    public static IEnumerable<string> GlyphNames { get { Load(); return glyphNames; } }

    /// <summary>Glyph sprite by file name (xbox_a, ps_cross, key_e, ...).</summary>
    public static Sprite Glyph(string name) { Load(); return glyphNames.Contains(name) ? Get("UI/Glyphs/" + name, Vector4.zero) : null; }

    /// <summary>Glyph name of a pad button in the current style (Xbox letters or PlayStation shapes).</summary>
    public static string GlyphName(Glyphs.Pad b, bool playStation)
    {
        switch (b)
        {
            case Glyphs.Pad.South: return playStation ? "ps_cross" : "xbox_a";
            case Glyphs.Pad.East: return playStation ? "ps_circle" : "xbox_b";
            case Glyphs.Pad.West: return playStation ? "ps_square" : "xbox_x";
            case Glyphs.Pad.North: return playStation ? "ps_triangle" : "xbox_y";
            case Glyphs.Pad.LB: return playStation ? "ps_l1" : "xbox_lb";
            case Glyphs.Pad.RB: return playStation ? "ps_r1" : "xbox_rb";
            case Glyphs.Pad.LT: return playStation ? "ps_l2" : "xbox_lt";
            case Glyphs.Pad.RT: return playStation ? "ps_r2" : "xbox_rt";
            case Glyphs.Pad.Start: return playStation ? "ps_options" : "xbox_menu";
            case Glyphs.Pad.Select: return playStation ? "ps_share" : "xbox_view";
            case Glyphs.Pad.LStick: return playStation ? "ps_l3" : "xbox_ls";
            case Glyphs.Pad.RStick: return playStation ? "ps_r3" : "xbox_rs";
            default: return playStation ? "ps_dpad" : "xbox_dpad";
        }
    }

    public static Sprite Glyph(Glyphs.Pad b) => Glyph(GlyphName(b, GameInput.IsPlayStation));

    /// <summary>Keyboard key glyph for a bracket token ("E", "Esc", "Enter", ...), or null.</summary>
    public static Sprite KeyGlyph(string token) => string.IsNullOrEmpty(token) ? null : Glyph("key_" + token.ToLowerInvariant());

    /// <summary>Icon of a crop id (wheat, potato, ...) with a generic fallback.</summary>
    public static Sprite CropIcon(string cropId) => Icon("crop_" + (cropId ?? "")) ?? Icon("crop_generic");

    private static Sprite Get(string path, Vector4 border)
    {
        Sprite s;
        if (cache.TryGetValue(path, out s) && s != null) return s;
        var tex = Resources.Load<Texture2D>(path);
        if (tex == null) return null;
        // Sprite.Create(texture, rect, pivot, pixelsPerUnit, extrude, meshType, border): border = (left, bottom, right, top)
        s = Sprite.Create(tex, new Rect(0f, 0f, tex.width, tex.height), new Vector2(0.5f, 0.5f), 100f, 0u, SpriteMeshType.FullRect, border);
        s.name = path;
        cache[path] = s;
        return s;
    }

    // ------------------------------------------------------------------ styling helpers

    /// <summary>Give an Image a 9-sliced kit sprite (tint white unless given). Returns false when the sprite is missing.</summary>
    public static bool Sliced(Image img, string kit, Color? tint = null)
    {
        if (img == null) return false;
        var s = Kit(kit);
        if (s == null) return false;
        img.sprite = s;
        img.type = Image.Type.Sliced;
        img.fillCenter = true;
        img.color = tint ?? Color.white;
        return true;
    }

    /// <summary>Colour to tint a kit panel with: white when the kit is drawn (the sprite carries the look), else the flat colour.</summary>
    public static Color PanelTint(Color flat) => Enabled ? Color.white : flat;

    /// <summary>An icon Image under parent (size px square, tinted). Null-safe: without the sprite the image is hidden.</summary>
    public static Image IconImage(Transform parent, string icon, float size, Color tint, string name = "Icon")
    {
        var rt = MenuKit.Rect(name, parent, typeof(Image));
        var img = rt.GetComponent<Image>();
        img.raycastTarget = false;
        rt.sizeDelta = new Vector2(size, size);
        SetIcon(img, icon, tint);
        return img;
    }

    public static void SetIcon(Image img, string icon, Color tint)
    {
        if (img == null) return;
        var s = Icon(icon) ?? Glyph(icon);
        img.sprite = s;
        img.type = Image.Type.Simple;
        img.preserveAspect = true;
        img.color = tint;
        img.enabled = s != null;
    }

    /// <summary>Progress bar: track + fill (fill anchored left, width = anchorMax.x). Returns the fill RectTransform.</summary>
    public static RectTransform Bar(Transform parent, string name, Vector2 size, string fillKit, out Image track, out Image fill)
    {
        var t = MenuKit.Rect(name, parent, typeof(Image));
        t.sizeDelta = size;
        track = t.GetComponent<Image>(); track.raycastTarget = false;
        if (!Sliced(track, "bar_track")) track.color = new Color(0f, 0f, 0f, 0.45f);
        var f = MenuKit.Rect("Fill", t, typeof(Image));
        f.anchorMin = new Vector2(0f, 0f); f.anchorMax = new Vector2(0f, 1f);
        f.offsetMin = f.offsetMax = Vector2.zero;
        fill = f.GetComponent<Image>(); fill.raycastTarget = false;
        if (!Sliced(fill, fillKit)) fill.color = Gold;
        return f;
    }

    /// <summary>Set a bar's fill to 0..1.</summary>
    public static void SetBar(RectTransform fill, float t) { if (fill != null) fill.anchorMax = new Vector2(Mathf.Clamp01(t), 1f); }

    // ------------------------------------------------------------------ design-system helpers

    /// <summary>Standard panel surface on an Image (flat kit sprite with a small baked shadow, or the flat colour).</summary>
    public static void Glass(Image img, bool plain = false)
    {
        if (img == null) return;
        if (!Sliced(img, plain ? "panel_plain" : "panel")) img.color = UiTheme.Glass;
    }

    /// <summary>"#RRGGBBAA" of a colour for TMP rich text.</summary>
    public static string Hex(Color c) => "#" + ColorUtility.ToHtmlStringRGBA(c);

    /// <summary>
    /// Key / button prompts as keycaps: every "[E]"-style token (after Glyphs.Apply, so pad labels too) is drawn as a
    /// small bold label on a translucent plate (TMP &lt;mark&gt;), the rest of the text is left alone. Mirrored
    /// "]E[" tokens of right-to-left lines are handled the same way.
    /// </summary>
    public static string Keycaps(string text)
    {
        if (string.IsNullOrEmpty(text) || (text.IndexOf('[') < 0 && text.IndexOf(']') < 0)) return text;
        var sb = new System.Text.StringBuilder(text.Length + 64);
        int i = 0;
        while (i < text.Length)
        {
            char c = text[i];
            if (c == '[' || c == ']')
            {
                char closeCh = c == '[' ? ']' : '[';
                int close = text.IndexOf(closeCh, i + 1);
                if (close > i + 1 && close - i <= 48)
                {
                    string token = text.Substring(i + 1, close - i - 1);
                    if (token.IndexOf(' ') < 0 && token.IndexOf('\n') < 0 && token.IndexOf('[') < 0 && token.IndexOf(']') < 0)
                    {
                        sb.Append(KeycapOpen).Append('\u00A0').Append(token).Append('\u00A0').Append(KeycapClose);
                        i = close + 1;
                        continue;
                    }
                }
            }
            sb.Append(c);
            i++;
        }
        return sb.ToString();
    }

    private const string KeycapOpen = "<mark=#FFFFFF30><b><color=#FFFFFF>", KeycapClose = "</color></b></mark>";

    /// <summary>Notification text on a dark glass plate (TMP &lt;mark&gt;, fades with the text alpha).</summary>
    public static string Toast(string msg) => string.IsNullOrEmpty(msg) ? msg : "<mark=#0E1114E0>\u00A0\u00A0" + msg.Replace("\n", "\u00A0\u00A0\n\u00A0\u00A0") + "\u00A0\u00A0</mark>";

    /// <summary>Small upper-case accent label above a heading or a HUD value.</summary>
    public static string Eyebrow(string s) => "<size=72%><color=" + UiTheme.AccentHex + "><b>" + (Loc.IsArabic ? s : (s ?? "").ToUpperInvariant()) + "</b></color></size>";

    /// <summary>Thin amber rule (Image) under a heading, on the reading side. Not part of any layout.</summary>
    public static Image Rule(RectTransform under, float width = 56f)
    {
        var rt = MenuKit.Rect("Rule", under, typeof(Image), typeof(LayoutElement));
        rt.GetComponent<LayoutElement>().ignoreLayout = true;
        var img = rt.GetComponent<Image>(); img.raycastTarget = false;
        if (!Sliced(img, "bar_fill")) img.color = UiTheme.Accent;
        rt.sizeDelta = new Vector2(width, 4f);
        PlaceRule(rt, Loc.IsArabic);
        return img;
    }

    public static void PlaceRule(RectTransform rule, bool rtl)
    {
        if (rule == null) return;
        float x = rtl ? 1f : 0f;
        rule.anchorMin = rule.anchorMax = new Vector2(x, 0f); rule.pivot = new Vector2(x, 1f);
        rule.anchoredPosition = new Vector2(0f, -2f);
    }

    /// <summary>Radial gauge ring (Image.Type.Filled, 270 degrees with the gap at the bottom). value 0..1.</summary>
    public static Image Arc(Transform parent, string name, float size, Color tint, float thickness = 1f)
    {
        var rt = MenuKit.Rect(name, parent, typeof(Image));
        rt.sizeDelta = new Vector2(size, size);
        rt.localRotation = Quaternion.Euler(0f, 0f, -45f);   // Radial360 from the bottom, clockwise: rotate so the 90 degree gap sits at 6 o'clock
        var img = rt.GetComponent<Image>(); img.raycastTarget = false;
        img.sprite = Kit(thickness < 0.5f ? "ring_thin" : "ring");
        img.type = Image.Type.Filled;
        img.fillMethod = Image.FillMethod.Radial360;
        img.fillOrigin = (int)Image.Origin360.Bottom;
        img.fillClockwise = true;
        img.fillAmount = 0.75f;
        img.color = tint;
        img.enabled = img.sprite != null;
        return img;
    }

    /// <summary>Set an Arc to 0..1 of its 270 degree sweep.</summary>
    public static void SetArc(Image arc, float t) { if (arc != null) arc.fillAmount = 0.75f * Mathf.Clamp01(t); }
}
